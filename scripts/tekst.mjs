/*
 * Запись текстового файла для Windows: метка кодировки и CRLF.
 *
 * Эти файлы открывают двойным щелчком — тем, что назначено в системе,
 * чаще всего Блокнотом. Без метки кодировки кириллица в UTF-8 рассыпается
 * в редакторах, которые её не угадывают; без CRLF весь промт слипается
 * в одну строку.
 *
 * Отдельным модулем, а не в каждом генераторе, потому что уже один раз
 * метка была проставлена разовой правкой файлов — и следующая же
 * перегенерация её стёрла. Правило должно жить там, где происходит
 * запись, иначе его забывают.
 */
import { writeFileSync } from 'node:fs';

const METKA = '\uFEFF';

export function zapisat(put, text) {
  const s = String(text).replace(/\r\n/g, '\n').replace(/\n/g, '\r\n');
  writeFileSync(put, (s.startsWith(METKA) ? s : METKA + s), 'utf8');
}
