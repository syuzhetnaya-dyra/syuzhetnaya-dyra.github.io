/*
 * Автор в промте стоит после «к произведению» — то есть в родительном
 * падеже: «Островского», а не «Островский». Склоняем фамилию, инициалы
 * оставляем как есть.
 */
function roditelnyy(avtor) {
  const chasti = avtor.split(' ');
  const familia = chasti.pop();
  const sklon = familia
    .replace(/(ский|ской|цкий|цкой)$/, (m) => m.slice(0, -2) + 'ого')
    .replace(/(ой|ый|ий)$/, 'ого')
    .replace(/(ова|ева|ина)$/, (m) => m.slice(0, -1) + 'ой')
    .replace(/(ая)$/, 'ой');
  return [...chasti, sklon === familia ? familia + 'а' : sklon].join(' ');
}

