/*
 * Стартовая скидка: один срок и две цены на весь сайт.
 *
 * Отдельным файлом, потому что об акции должны знать в двух местах сразу —
 * продающий блок на главной и замок внутри платных страниц. Если цену
 * написать в двух местах руками, однажды на главной будет 490, а в замке
 * 980, и покупатель решит, что его обманывают.
 *
 * СРОК ЗАДАН С ЧАСОВЫМ ПОЯСОМ. «26 октября 23:59» без пояса — это разный
 * момент в Москве, Новосибирске и Калининграде: ученик из Владивостока
 * увидел бы, что скидка кончилась, когда в Москве ещё полдень. Поэтому в
 * строке стоит +03:00, а дальше всё считается в абсолютном времени
 * (Date.parse даёт миллисекунды от эпохи, одинаковые в любом поясе).
 *
 * ОТСЧЁТ НЕ СБРАСЫВАЕТСЯ ОТ ОБНОВЛЕНИЯ СТРАНИЦЫ по той же причине: он не
 * хранит «сколько осталось», а каждый раз вычитает текущее время из этого
 * срока. Ничего сохранять и не нужно.
 *
 * ПОСЛЕ СРОКА кнопка исчезает, и на её месте не появляется никакой
 * другой. Причина простая: многоразовый счёт ЮKassa выставлен на
 * фиксированную сумму, и ссылка в SSYLKA_OPLATY списала бы 490 ₽ и
 * двадцать седьмого октября. Ссылки на 980 ₽ пока нет, а показывать
 * оплату, которой нет, нельзя. Поэтому после срока на странице остаётся
 * только цена как сведение — и строка о том, что скидка закончилась.
 */

export const SROK_TEKST = '2026-10-26T23:59:59+03:00';

/** Абсолютный момент окончания акции, миллисекунды от эпохи. */
export const SROK = Date.parse(SROK_TEKST);

/** Как срок называют словами на странице. */
export const SROK_SLOVAMI = '26 октября';

export const CENA_AKTSIYA = 490;
export const CENA_POSLE = 980;

/*
 * Пробел перед «₽» неразрывный: иначе цена переносится по строкам, и в
 * конце строки остаётся «490», а знак рубля уезжает на следующую.
 */
export const rubli = (n) => `${n} ₽`;

/** Идёт ли акция в данный момент. */
export const aktsiyaIdyot = (teper = Date.now()) => teper < SROK;

/** Цена, которую нужно показывать сейчас. */
export const cenaSejchas = (teper = Date.now()) =>
  aktsiyaIdyot(teper) ? CENA_AKTSIYA : CENA_POSLE;

/*
 * Срок жизни доступа. Решение заказчика: 490 ₽ за 12 месяцев с момента
 * оплаты, разовый платёж, без автопродления.
 *
 * Техническая правда, которую надо знать: замок истечь не может. Сайт —
 * статика, сервера нет, ключ лежит у покупателя в браузере, и отобрать
 * его через год некому. То есть купивший фактически получает доступ
 * насовсем. Обещание «12 месяцев» он при этом получает выполненным с
 * запасом, так что обмана тут нет — но и ограничивать доступ сайт не
 * умеет, и писать в будущем «подписка кончилась» будет неправдой.
 */
export const SROK_DOSTUPA = '12 месяцев';
