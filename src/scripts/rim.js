// Римские цифры.
//
// Раньше они лежали массивами — ['I'…'V'] в чеке, ['I'…'VI'] на развороте.
// Пока произведение было одно, это работало; у «Войны и мира» шестнадцать
// полных карточек, и седьмая получила бы пустоту. Пустоту без ошибки, что
// хуже: сборка прошла бы, а цифра исчезла.

const ZNAKI = [
  [1000, 'M'], [900, 'CM'], [500, 'D'], [400, 'CD'],
  [100, 'C'], [90, 'XC'], [50, 'L'], [40, 'XL'],
  [10, 'X'], [9, 'IX'], [5, 'V'], [4, 'IV'], [1, 'I'],
];

export function rim(n) {
  let ost = Math.floor(Number(n) || 0);
  if (ost < 1) return '';
  let out = '';
  for (const [v, z] of ZNAKI) {
    while (ost >= v) {
      out += z;
      ost -= v;
    }
  }
  return out;
}
